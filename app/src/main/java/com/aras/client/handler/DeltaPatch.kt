package com.aras.client.handler

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.withContext
import java.io.BufferedOutputStream
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.io.IOException
import java.io.InputStream
import java.io.RandomAccessFile
import java.util.Arrays
import java.util.zip.Inflater
import java.util.zip.InflaterInputStream
import kotlin.coroutines.coroutineContext

/**
 * Applies ARASDLT1 delta patches and produces the target APK byte-for-byte.
 *
 * Layout, every integer little-endian:
 *   0..7    magic "ARASDLT1"
 *   8..15   length of the compressed control stream
 *   16..23  length of the compressed diff stream
 *   24..31  length of the compressed extra stream
 *   32..39  size of the reconstructed APK
 *   40..47  size of the installed APK the patch applies to
 *   then    three zlib streams: control triples, diff bytes, extra bytes
 *
 * The streams carry the same content bsdiff produces (triples use 8-byte
 * signed-magnitude encoding), recompressed with zlib so applying needs only
 * java.util.zip. Patches are generated by tools/make_delta_patch.py.
 */
object DeltaPatch {

    private const val HEADER_SIZE = 48L
    private const val BUFFER_SIZE = 64 * 1024
    private const val PROGRESS_STEP = 1024L * 1024L
    private const val FREE_SPACE_SLACK = 16L * 1024L * 1024L
    private val MAGIC = "ARASDLT1".toByteArray(Charsets.US_ASCII)

    suspend fun apply(
        oldFile: File,
        patchFile: File,
        outputFile: File,
        onProgress: (bytesWritten: Long, totalBytes: Long) -> Unit = { _, _ -> }
    ): File = withContext(Dispatchers.IO) {
        if (!oldFile.isFile) throw IOException("Installed APK is missing")
        if (!patchFile.isFile) throw IOException("Delta patch is missing")

        val header = readHeader(patchFile)
        if (oldFile.length() != header.oldSize) {
            throw IOException("Delta patch does not match the installed APK")
        }
        val available = outputFile.parentFile?.usableSpace ?: 0L
        if (available in 1 until header.newSize + FREE_SPACE_SLACK) {
            throw IOException("Not enough free space to apply the update")
        }

        val parent = outputFile.parentFile
        if (parent != null && !parent.isDirectory && !parent.mkdirs()) {
            throw IOException("Unable to create update directory")
        }

        try {
            applyStreams(oldFile, patchFile, header, outputFile, onProgress)
            outputFile
        } catch (e: Exception) {
            outputFile.delete()
            throw e
        }
    }

    private suspend fun applyStreams(
        oldFile: File,
        patchFile: File,
        header: Header,
        outputFile: File,
        onProgress: (Long, Long) -> Unit
    ) {
        val diffOffset = HEADER_SIZE + header.ctrlLength
        val extraOffset = diffOffset + header.diffLength
        openStream(patchFile, HEADER_SIZE).use { ctrl ->
            openStream(patchFile, diffOffset).use { diff ->
                openStream(patchFile, extraOffset).use { extra ->
                    RandomAccessFile(oldFile, "r").use { old ->
                        BufferedOutputStream(FileOutputStream(outputFile), BUFFER_SIZE).use { out ->
                            copyPatchStreams(
                                old = old,
                                ctrl = ctrl,
                                diff = diff,
                                extra = extra,
                                newSize = header.newSize,
                                out = out,
                                onProgress = onProgress
                            )
                        }
                    }
                }
            }
        }
    }

    private suspend fun copyPatchStreams(
        old: RandomAccessFile,
        ctrl: InputStream,
        diff: InputStream,
        extra: InputStream,
        newSize: Long,
        out: BufferedOutputStream,
        onProgress: (Long, Long) -> Unit
    ) {
        val triple = ByteArray(24)
        val diffBuffer = ByteArray(BUFFER_SIZE)
        val oldBuffer = ByteArray(BUFFER_SIZE)
        val outBuffer = ByteArray(BUFFER_SIZE)
        var oldPos = 0L
        var newPos = 0L
        var lastReported = 0L
        onProgress(0L, newSize)

        while (newPos < newSize) {
            coroutineContext.ensureActive()
            if (!readFully(ctrl, triple, triple.size)) throw IOException("Corrupt delta patch")
            val diffLength = decodeSigned(triple, 0)
            val extraLength = decodeSigned(triple, 8)
            val seekLength = decodeSigned(triple, 16)
            if (diffLength < 0 || extraLength < 0 || oldPos < 0 ||
                diffLength > newSize - newPos ||
                extraLength > newSize - newPos - diffLength
            ) {
                throw IOException("Corrupt delta patch")
            }

            old.seek(oldPos)
            var remaining = diffLength
            while (remaining > 0) {
                coroutineContext.ensureActive()
                val chunk = minOf(remaining, BUFFER_SIZE.toLong()).toInt()
                readFullyOrThrow(diff, diffBuffer, chunk)
                readOld(old, oldBuffer, chunk)
                for (i in 0 until chunk) {
                    outBuffer[i] = (diffBuffer[i].toInt() + oldBuffer[i].toInt()).toByte()
                }
                out.write(outBuffer, 0, chunk)
                remaining -= chunk
                newPos += chunk
                if (newPos - lastReported >= PROGRESS_STEP) {
                    lastReported = newPos
                    onProgress(newPos, newSize)
                }
            }

            try {
                oldPos = Math.addExact(oldPos, diffLength)
                oldPos = Math.addExact(oldPos, seekLength)
            } catch (e: ArithmeticException) {
                throw IOException("Corrupt delta patch", e)
            }

            remaining = extraLength
            while (remaining > 0) {
                coroutineContext.ensureActive()
                val chunk = minOf(remaining, BUFFER_SIZE.toLong()).toInt()
                readFullyOrThrow(extra, diffBuffer, chunk)
                out.write(diffBuffer, 0, chunk)
                remaining -= chunk
                newPos += chunk
                if (newPos - lastReported >= PROGRESS_STEP) {
                    lastReported = newPos
                    onProgress(newPos, newSize)
                }
            }
        }

        onProgress(newPos, newSize)
    }

    private fun readHeader(patchFile: File): Header {
        val raw = ByteArray(HEADER_SIZE.toInt())
        FileInputStream(patchFile).use { input ->
            if (!readFully(input, raw, raw.size)) throw IOException("Delta patch is truncated")
        }
        if (!raw.copyOfRange(0, MAGIC.size).contentEquals(MAGIC)) {
            throw IOException("Unsupported delta patch format")
        }
        val ctrlLength = readLong(raw, 8)
        val diffLength = readLong(raw, 16)
        val extraLength = readLong(raw, 24)
        val newSize = readLong(raw, 32)
        val oldSize = readLong(raw, 40)
        if (ctrlLength <= 0 || diffLength <= 0 || extraLength <= 0 || newSize <= 0 || oldSize <= 0) {
            throw IOException("Corrupt delta patch header")
        }
        val expectedLength = try {
            Math.addExact(
                HEADER_SIZE,
                Math.addExact(ctrlLength, Math.addExact(diffLength, extraLength))
            )
        } catch (e: ArithmeticException) {
            throw IOException("Corrupt delta patch header", e)
        }
        if (expectedLength != patchFile.length()) throw IOException("Corrupt delta patch length")
        return Header(ctrlLength, diffLength, extraLength, newSize, oldSize)
    }

    private fun openStream(patchFile: File, offset: Long): InflaterInputStream {
        val input = FileInputStream(patchFile)
        try {
            var remaining = offset
            while (remaining > 0) {
                val skipped = input.skip(remaining)
                if (skipped <= 0) throw IOException("Corrupt delta patch offsets")
                remaining -= skipped
            }
        } catch (e: Exception) {
            input.close()
            throw e
        }
        return InflaterInputStream(input, Inflater(), BUFFER_SIZE)
    }

    private fun readOld(old: RandomAccessFile, buffer: ByteArray, length: Int) {
        var read = 0
        while (read < length) {
            val count = old.read(buffer, read, length - read)
            if (count < 0) break
            read += count
        }
        if (read < length) Arrays.fill(buffer, read, length, 0)
    }

    private fun readLong(buffer: ByteArray, offset: Int): Long {
        var value = 0L
        for (i in 0 until 8) {
            value = value or ((buffer[offset + i].toLong() and 0xFF) shl (8 * i))
        }
        return value
    }

    /** bsdiff stores a negative number by setting the high bit of the last byte. */
    private fun decodeSigned(buffer: ByteArray, offset: Int): Long {
        val raw = readLong(buffer, offset)
        val magnitude = raw and Long.MAX_VALUE
        return if (raw < 0) -magnitude else magnitude
    }

    private fun readFully(input: InputStream, buffer: ByteArray, length: Int): Boolean {
        var read = 0
        while (read < length) {
            val count = input.read(buffer, read, length - read)
            if (count < 0) return false
            read += count
        }
        return true
    }

    private fun readFullyOrThrow(input: InputStream, buffer: ByteArray, length: Int) {
        if (!readFully(input, buffer, length)) throw IOException("Corrupt delta patch")
    }

    private data class Header(
        val ctrlLength: Long,
        val diffLength: Long,
        val extraLength: Long,
        val newSize: Long,
        val oldSize: Long
    )
}
